"""
import_colonies.py

Standalone script (NOT a management command) to bulk-import Colony rows
from a JSON list of {name, latitude, longitude} dicts.

USAGE
-----
1. Activate your venv:
       source venv/bin/activate        (or your venv's activate script)

2. Edit the two CONFIG values below:
       DJANGO_SETTINGS_MODULE  -> your project's settings module
       from myapp.models import Company, Colony  -> your actual app name

3. Run it from your project root (same folder as manage.py):
       python import_colonies.py

The script is safe to re-run: it uses get_or_create so it won't create
duplicate Colony rows for the same name+owner on a second run.
"""

import os
import sys
import json

# ── CONFIG: EDIT THESE TWO LINES ────────────────────────────────────────
os.environ.setdefault("DJANGO_SETTINGS_MODULE", "config.settings.dev")  # <-- change this
# ─────────────────────────────────────────────────────────────────────────

import django

# Make sure Django can find your project (adjust if this script lives elsewhere)
PROJECT_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "../../.."))
if PROJECT_ROOT not in sys.path:
    sys.path.insert(0, PROJECT_ROOT)

django.setup()

# <-- change "myapp" to the actual app that contains Company and Colony
from apps.managements.models import Company, Colony  # noqa: E402


# ── Placeholder values (edit if you want different behavior) ───────────
PLACEHOLDER_COMPANY_NAME = "Imported Colonies Company"
PLACEHOLDER_LOCATION_URL = "https://example.com/placeholder"
# ─────────────────────────────────────────────────────────────────────────

 

# If you'd rather load from a JSON file instead of the inline list above,
