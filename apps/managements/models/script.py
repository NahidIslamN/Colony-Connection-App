def get_or_create_owner():
    """Get (or create) the placeholder Company that will own imported colonies."""
    from datetime import date

    company, created = Company.objects.get_or_create(
        company_name=PLACEHOLDER_COMPANY_NAME,
        defaults={
            "ceo_name": "N/A",
            "expire_date": date(2099, 12, 31),
        },
    )
    if created:
        print(f"Created placeholder company: {company.company_name} (id={company.pk})")
    else:
        print(f"Using existing placeholder company: {company.company_name} (id={company.pk})")
    return company


def import_colonies():
    owner = get_or_create_owner()

    created_count = 0
    skipped_count = 0

    for row in COLONY_DATA:
        name = row.get("name")
        lat = row.get("latitude")
        lng = row.get("longitude")

        if name is None or lat is None or lng is None:
            print(f"Skipping incomplete row: {row}")
            skipped_count += 1
            continue

        colony, created = Colony.objects.get_or_create(
            name=name,
            colony_owner=owner,
            defaults={
                "latitude": lat,
                "longitude": lng,
                "location_url": PLACEHOLDER_LOCATION_URL,
                "status": "active",
                "is_public":True,
            },
        )

        if created:
            print(f"  + Created: {colony.name}")
            created_count += 1
        else:
            print(f"  = Already exists, skipped: {colony.name}")
            skipped_count += 1

    print("\nDone.")
    print(f"  Created: {created_count}")
    print(f"  Skipped (already existed or incomplete): {skipped_count}")


if __name__ == "__main__":
    import_colonies()